#!/usr/bin/env bash
# Shared by scripts/exchange-failover.sh and scripts/exchange-bench.sh: build, one
# configuration file, a pre-shared key, and functions to start and find every process
# of the exchange (MG matching groups and NS ledger shards of 3 replicas each, a
# forwarder per shard, one settler, a tick driver, an audit). Source it, then call
# start_cluster. Settings (environment): SHARDS (2), MGROUPS (2), BASE_PORT, PROFILE
# (release), FSYNC (relaxed:10), CHAOS (5), AUTH (1), KEEP, KEEP_ALIVE.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
NS=${SHARDS:-2}
MG=${MGROUPS:-2}
PARTS=4
BASE=${BASE_PORT:-47500}
PROFILE=${PROFILE:-release}
FSYNC=${FSYNC:-relaxed:10}
CHAOS=${CHAOS:-5} # every 5th relay delivery is also duplicated, overlapped or sent out of order (0 = off)
BIN=target/$PROFILE

if [[ "$PROFILE" == release ]]; then
  cargo build --release -q -p orderer-cluster --bin orderer-load -p orderer-exchange --bins
else
  cargo build -q -p orderer-cluster --bin orderer-load -p orderer-exchange --bins
fi

TMP=$(mktemp -d)
CONF="$TMP/exchange.conf"
cat >"$CONF" <<EOF
# generated by scripts/exchange-failover.sh
ledger_shards   = $NS
matching_groups = $MG
partitions      = $PARTS
fee_ppm         = 500
symbol = 10 base=1 quote=2 lot=1000
symbol = 11 base=3 quote=2 lot=10 maker_ppm=100 taker_ppm=300
symbol = 12 base=4 quote=2 lot=1
symbol = 13 base=5 quote=2 lot=1
symbol = 14 base=6 quote=2 lot=1
symbol = 15 base=7 quote=2 lot=1
EOF
if [[ "${AUTH:-1}" != 0 ]]; then
  ORDERER_KEY=$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
  export ORDERER_KEY
else
  unset ORDERER_KEY
fi
LOAD_PID=
AUDIT_PID=
declare -a TIER_PID=()
declare -a LED_PID=()
declare -a FWD_PID=()
SET_PID=0
TICK_PID=0
for ((i = 0; i < MG * 3; i++)); do TIER_PID[$i]=0; done
for ((i = 0; i < NS * 3; i++)); do LED_PID[$i]=0; done
for ((s = 0; s < NS; s++)); do FWD_PID[$s]=0; done

# --- addresses -------------------------------------------------------------
tier_port() { echo $((BASE + $1 + 500 + $2 * 10 + $3)); } # kind offset, group, node
tier_members() { local g=$1; echo "0=127.0.0.1:$(tier_port 0 "$g" 0),1=127.0.0.1:$(tier_port 0 "$g" 1),2=127.0.0.1:$(tier_port 0 "$g" 2)"; }
tier_clients() { local g=$1; echo "127.0.0.1:$(tier_port 100 "$g" 0),127.0.0.1:$(tier_port 100 "$g" 1),127.0.0.1:$(tier_port 100 "$g" 2)"; }
tier_exchange() { local g=$1; echo "127.0.0.1:$(tier_port 200 "$g" 0),127.0.0.1:$(tier_port 200 "$g" 1),127.0.0.1:$(tier_port 200 "$g" 2)"; }
led_port() { echo $((BASE + $1 + 10 + $2 * 10 + $3)); } # kind offset, shard, node
led_members() { local s=$1; echo "0=127.0.0.1:$(led_port 0 "$s" 0),1=127.0.0.1:$(led_port 0 "$s" 1),2=127.0.0.1:$(led_port 0 "$s" 2)"; }
led_clients() { local s=$1; echo "127.0.0.1:$(led_port 100 "$s" 0),127.0.0.1:$(led_port 100 "$s" 1),127.0.0.1:$(led_port 100 "$s" 2)"; }
led_gateways() { local s=$1; echo "127.0.0.1:$(led_port 200 "$s" 0),127.0.0.1:$(led_port 200 "$s" 1),127.0.0.1:$(led_port 200 "$s" 2)"; }
join_n() { local n=$1 fn=$2 out="" i; for ((i = 0; i < n; i++)); do out+="${out:+;}$("$fn" "$i")"; done; echo "$out"; }
ALL_GATEWAYS=$(join_n "$NS" led_gateways)
ALL_CLIENTS=$(join_n "$NS" led_clients)
ALL_TIER_EX=$(join_n "$MG" tier_exchange)
ALL_TIER_CL=$(join_n "$MG" tier_clients)

cleanup() {
  local rc=$?
  if [[ -n "${KEEP_ALIVE:-}" && $rc -ne 0 ]]; then
    echo "KEEP_ALIVE: failed (status $rc); processes still running, logs in $TMP"
    return
  fi
  local p
  for p in "${TIER_PID[@]}" "${LED_PID[@]}" "${FWD_PID[@]}" "$SET_PID" "$TICK_PID" "${LOAD_PID:-0}" "${AUDIT_PID:-0}"; do
    [[ "$p" != 0 && -n "$p" ]] && kill -9 "$p" 2>/dev/null || true
  done
  if [[ $rc -ne 0 ]]; then echo "FAILED (status $rc); logs kept in $TMP"; return; fi
  [[ -z "${KEEP:-}" ]] && rm -rf "$TMP"
  return 0
}
trap cleanup EXIT

# --- process control -------------------------------------------------------
start_tier() {
  local g=$1 i=$2
  "$BIN/tier-node" --config "$CONF" --group "$g" --id "$i" --members "$(tier_members "$g")" \
    --client "127.0.0.1:$(tier_port 100 "$g" "$i")" --exchange "127.0.0.1:$(tier_port 200 "$g" "$i")" \
    --dir "$TMP/tier$g-$i" --compact-every 4000 --digest-every 2000 --fsync "$FSYNC" >>"$TMP/tier$g-$i.log" 2>&1 &
  TIER_PID[$((g * 3 + i))]=$!
}
start_ledger() {
  local s=$1 i=$2
  "$BIN/ledger-node" --config "$CONF" --shard "$s" --id "$i" --members "$(led_members "$s")" \
    --client "127.0.0.1:$(led_port 100 "$s" "$i")" --gateway "127.0.0.1:$(led_port 200 "$s" "$i")" \
    --dir "$TMP/ledger$s-$i" --compact-every 4000 --digest-every 2000 --fsync "$FSYNC" >>"$TMP/ledger$s-$i.log" 2>&1 &
  LED_PID[$((s * 3 + i))]=$!
}
start_fwd() {
  local s=$1
  "$BIN/exchange-relay" forwarder --config "$CONF" --shard "$s" --ledger "$(led_gateways "$s")" --tier "$ALL_TIER_EX" \
    --chaos "$CHAOS" >>"$TMP/fwd$s.log" 2>&1 &
  FWD_PID[$s]=$!
}
start_set() {
  "$BIN/exchange-relay" settler --config "$CONF" --ledgers "$ALL_GATEWAYS" --tier "$ALL_TIER_EX" \
    --chaos "$CHAOS" >>"$TMP/set.log" 2>&1 &
  SET_PID=$!
}
start_tick() {
  "$BIN/exchange-relay" tick --config "$CONF" --ledgers "$ALL_GATEWAYS" --interval-ms 200 --sweep-every-ms 2000 \
    --max-age-ms 6000 --retry-ms 6000 >>"$TMP/tick.log" 2>&1 &
  TICK_PID=$!
}
start_audit() {
  "$BIN/exchange-audit" --config "$CONF" --ledgers "$ALL_GATEWAYS" --tier "$ALL_TIER_EX" \
    --ledger-clients "$ALL_CLIENTS" --tier-clients "$ALL_TIER_CL" --interval-ms 1000 >>"$TMP/audit.log" 2>&1 &
  AUDIT_PID=$!
}

# the node id of the current leader of a group, given its client addresses
leader_of() {
  "$BIN/orderer-load" status --clients "$1" 2>/dev/null | grep "role=Leader" | head -1 | sed -E 's/.*id=([0-9]+).*/\1/'
}
wait_leader() {
  local what=$1 clients=$2 _
  for _ in $(seq 1 150); do [[ -n "$(leader_of "$clients")" ]] && return 0; sleep 0.1; done
  echo "FAIL: no leader elected for $what"
  exit 1
}
start_cluster() {
for ((g = 0; g < MG; g++)); do for i in 0 1 2; do start_tier "$g" "$i"; done; done
for ((s = 0; s < NS; s++)); do for i in 0 1 2; do start_ledger "$s" "$i"; done; done
if [[ -n "${ORDERER_KEY:-}" ]]; then AUTHSTATE=on; else AUTHSTATE=off; fi
echo "started $MG matching groups and $NS ledger shards, 3 replicas each, auth $AUTHSTATE (logs in $TMP)"
for ((g = 0; g < MG; g++)); do wait_leader "matching group $g" "$(tier_clients "$g")"; done
for ((s = 0; s < NS; s++)); do wait_leader "ledger shard $s" "$(led_clients "$s")"; done
for ((s = 0; s < NS; s++)); do start_fwd "$s"; done
start_set
start_tick
sleep 1
}
